import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const backendDirectory = path.resolve(scriptDirectory, '..');
const sourceDirectory = path.join(backendDirectory, 'src', 'data', 'openings-source');
const outputPath = path.join(backendDirectory, 'src', 'data', 'chessOpenings.generated.js');

const openings = [];

for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const source = await readFile(path.join(sourceDirectory, `${letter}.tsv`), 'utf8');
  const [, ...lines] = source.replace(/^\uFEFF/, '').split(/\r?\n/);

  for (const line of lines) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    if (!eco || !name || !pgn) continue;
    openings.push({ eco, name, pgn });
  }
}

openings.sort((left, right) => (
  left.eco.localeCompare(right.eco)
  || left.name.localeCompare(right.name)
  || left.pgn.localeCompare(right.pgn)
));

const banner = [
  '// Generated by scripts/build-chess-openings.mjs.',
  '// Source: https://github.com/lichess-org/chess-openings (CC0-1.0).',
  '// Do not edit this file manually.',
  ''
].join('\n');

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `${banner}export const CHESS_OPENINGS = ${JSON.stringify(openings, null, 2)};\n`,
  'utf8'
);

console.log(`Generated ${openings.length} opening positions at ${outputPath}`);
